#!/usr/bin/env python3
"""Generate native C++ coefficient tables ONLY from independent ngspice CSV.

Usage: python3 scripts/generate_spice_reference.py \
  golden/altec/long_steady.csv golden/rs124/long_steady.csv \
  plugin/SpiceReferenceMeasured.inc
The source CSV is generated by SPICE, never by the DSP under test.
C++ tables have K2..K20, 9 input levels, 80/100% attenuator, 2 modes.
"""
import csv,sys,hashlib
from pathlib import Path

if len(sys.argv)!=4:
 raise SystemExit("Expected Altec CSV, RS124 CSV, output include")
mode_files=[("altec",Path(sys.argv[1]),"A-436B"),
            ("rs",Path(sys.argv[2]),"RS124")]
def f(v):
 x=float(v)
 if not -1e10<x<1e10:raise ValueError("Nonfinite/large datum")
 s=f"{x:.8g}"
 if "." not in s and "e" not in s:s+="."
 return s+"f"
output=[
 "// Automatically generated from independent ngspice 1.6s SPICE results.",
 "// DO NOT hand-edit values. Regenerate with generate_spice_reference.py.",
 "// Regenerate and compare before declaring a new VST3 parity result.",
]
for short,path,mode in mode_files:
 data=path.read_bytes()
 output.append(f"// {mode} source SHA256: {hashlib.sha256(data).hexdigest()}")
 with path.open(newline="") as fp:rows=list(csv.DictReader(fp))
 assert all(x["mode"]==mode and x["status"]=="OK" for x in rows)
 for knob in (80,100):
  chosen=sorted((x for x in rows if int(x["input_pct"])==knob),
                key=lambda x:float(x["input_dBu"]))
  levels=[int(float(x["input_dBu"])) for x in chosen]
  assert len(chosen)==9 and levels==[-24,-18,-12,-6,0,3,7,10,13],(mode,knob,levels)
  output.append(f"static constexpr std::array<Point,9> {short}{knob} {{{{")
  for x in chosen:
   hs=[f(x[f"K{k}_dBc"]) for k in range(2,21)]
   line=("  {"+",".join([f(x["input_dBu"]),f(x["final_output_dBu"]),
     f(-float(x["final_CV_V"])),f(x["final_THD_percent"])])+
     ",{"+",".join(hs)+"}},")
   output.append(line)
  output.append("}};")
  output.append("")
dest=Path(sys.argv[3])
dest.parent.mkdir(parents=True,exist_ok=True)
dest.write_text("\n".join(output)+"\n")
print(f"Generated {dest}: {len(output)} lines, 36 SPICE points, K2..K20")
