#!/usr/bin/env python3
"""Fail-closed SPICE / native DSP calibration comparison.

The reference CSVs are INDEPENDENT ngspice outputs, never generated by DSP.
These 36/1k tests are a PARTIAL subset of the user's required all-control,
all-frequency validation. Passing cannot certify the complete VST3.
"""
import argparse,csv,json,math
from pathlib import Path

p=argparse.ArgumentParser()
p.add_argument("--reference-altec",required=True)
p.add_argument("--reference-rs124",required=True)
p.add_argument("--dsp",required=True)
p.add_argument("--output",default="output/vst3_spice_parity")
p.add_argument("--tolerance",type=float,default=8.)
args=p.parse_args()
out=Path(args.output);out.mkdir(parents=True,exist_ok=True)
reference=[]
for fn in (args.reference_altec,args.reference_rs124):
 with open(fn,newline="") as fp:reference.extend(csv.DictReader(fp))
with open(args.dsp,newline="") as fp:dsp=list(csv.DictReader(fp))
key=lambda x:(x["mode"],int(float(x["input_pct"])),int(float(x["input_dBu"])))
expected={key(x):x for x in reference}
actual={key(x):x for x in dsp}
issues=[]
rows=[]
def evaluate(key_,label,expected_,actual_,kind):
 if kind=="amplitude":
  err=100.*abs(10**((actual_-expected_)/20.)-1.)
 elif kind=="ratio":
  err=100.*abs(actual_-expected_)/max(0.02,abs(expected_))
 elif kind=="harmonic":
  # 8% harmonic AMPLITUDE deviation is ≈0.67 dB; near the
  # SPICE -90dBc floor we report the deviation, do not certify it.
  err=100.*abs(10**((actual_-expected_)/20.)-1.)
 else:raise RuntimeError("Invalid metric")
 ok=math.isfinite(err) and err<=args.tolerance
 row=dict(mode=key_[0],input_pct=key_[1],input_dBu=key_[2],
          metric=label,reference=expected_,measured=actual_,
          error_pct=round(err,3),pass_8pct=ok)
 rows.append(row)
 if not ok:issues.append(row)
for key_,ref in expected.items():
 if key_ not in actual:
  issues.append(dict(missing_dsp_case=key_));continue
 x=actual[key_]
 evaluate(key_,"output_amplitude",float(ref["final_output_dBu"]),
          float(x["final_output_dBu"]),"amplitude")
 evaluate(key_,"THD",float(ref["final_THD_percent"]),
          float(x["final_THD_percent"]),"ratio")
 evaluate(key_,"CV_magnitude",abs(float(ref["final_CV_V"])),
          float(x["CV_magnitude_V"]),"ratio")
 for k in range(2,21):
  field=f"K{k}_dBc"
  if not ref[field] or not x[field]:continue
  exp=float(ref[field]);obs=float(x[field])
  # Very weak bins are dominated by SPICE numerical floor; they must be
  # calibrated later with a noise-floor-aware absolute error rule.
  if exp <= -85.:
   continue
  evaluate(key_,field,exp,obs,"harmonic")
missing_ref=sorted(set(actual).difference(expected))
for k in missing_ref:issues.append(dict(missing_spice_case=k))
with (out/"parity_by_metric.csv").open("w",newline="") as fp:
 w=csv.DictWriter(fp,fieldnames=["mode","input_pct","input_dBu","metric",
             "reference","measured","error_pct","pass_8pct"])
 w.writeheader();w.writerows(rows)
summary=dict(reference_cases=len(expected),dsp_cases=len(actual),
             tested_metrics=len(rows),failed_metrics=len(issues),
             tolerance_pct=args.tolerance,
             max_error_pct=max((r["error_pct"] for r in rows),default=None),
             failures=issues[:80],
             qualification="PARTIAL_1KHZ_2_INPUT_CONTROLS_ONLY")
(out/"parity_summary.json").write_text(json.dumps(summary,indent=2))
print("PARITY SUMMARY",json.dumps({k:v for k,v in summary.items()
                         if k!="failures"},indent=2),flush=True)
for v in sorted((r for r in issues if "error_pct" in r),
                key=lambda x:x["error_pct"],reverse=True)[:22]:
 print("PARITY_FAIL",v,flush=True)
if issues:
 raise SystemExit(1)
print("PASS: 1kHz subset within tolerance; all-controls and FR/phase not certified")
